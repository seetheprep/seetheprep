function inferCategories(cuisine: string): string[] {
  if (/coffee|espresso/i.test(cuisine)) return ["coffee"];
  if (/pizza|flatbread/i.test(cuisine)) return ["pasta"];
  if (/fish|seafood/i.test(cuisine)) return ["fish-chips"];
  if (/chicken|wings/i.test(cuisine)) return ["fried-chicken"];
  if (/dessert|French/i.test(cuisine)) return ["desserts"];
  if (/wok|noodles|stir|teppan|clay/i.test(cuisine)) return ["ramen", "thai"];
  return ["burgers"];
}
